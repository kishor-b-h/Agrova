// ============ CROP RECOMMENDATION ============
export function recommendCrops(temp, humidity) {
  const recommendations = [];
  cropsData.forEach(crop => {
    const tempRange = crop.temp.match(/(\d+)-(\d+)/);
    if (tempRange) {
      const minT = parseInt(tempRange[1]);
      const maxT = parseInt(tempRange[2]);
      if (temp >= minT - 5 && temp <= maxT + 5) {
        recommendations.push(crop);
      }
    }
  });
  return recommendations.slice(0, 12);
}
